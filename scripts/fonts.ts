#!/usr/bin/env node
/* Materialise fonts/ from the @fontsource-variable packages.

   The brand faces are a dependency, not a checked-in binary: npm owns the
   version and `fonts/` is output. It still has to be real files on disk,
   because a rendered design resolves `styles.css` and cannot reach into
   node_modules. Only the styles and subsets this system uses, and only woff2.
   The container entrypoint runs it whenever `fonts/` is absent. Then it
   measures the width of each character in a browser. A diagram uses these
   widths to wrap text, and to refuse text that does not fit.

     make fonts
*/
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from 'playwright';
import subsetFont from 'subset-font';

import { FRONTEND, ROOT } from './lib/cards.ts';
import * as report from './lib/report.ts';

/* The faces the design system declares. A variable face covers every weight
   the tokens expose, so this list only chooses styles and subsets. */
const FAMILIES = [
  {
    pkg: '@fontsource-variable/source-sans-3',
    family: 'Source Sans 3',
    styles: ['normal', 'italic'],
  },
  {
    pkg: '@fontsource-variable/source-code-pro',
    family: 'Source Code Pro',
    styles: ['normal'],
  },
];
const SUBSETS = ['latin', 'latin-ext'];

const OUT = join(FRONTEND, 'fonts');
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const blocks = [];
let copied = 0;

for (const { pkg, family, styles } of FAMILIES) {
  const base = join(ROOT, 'node_modules', pkg);
  const slug = pkg.split('/')[1];
  for (const style of styles) {
    /* The complete stylesheet carries unicode-range; the per-subset files
       omit it. The ranges stop the browser from a fetch of both subsets. */
    const cssName = `wght${style === 'italic' ? '-italic' : ''}.css`;
    let css;
    try {
      css = readFileSync(join(base, cssName), 'utf8');
    } catch {
      throw new Error(`${pkg}/${cssName} is absent — does that style exist upstream?`);
    }
    for (const subset of SUBSETS) {
      const fileName = `${slug}-${subset}-wght-${style}.woff2`;
      const block = css
        .split('@font-face')
        .find((b) => b.includes(`/files/${fileName}`));
      if (!block) throw new Error(`${pkg}: no ${subset} face for ${style}`);
      const range = /unicode-range:\s*([^;]+);/.exec(block);

      copyFileSync(join(base, 'files', fileName), join(OUT, fileName));
      copied++;
      blocks.push(`@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: 200 900;
  font-display: optional;
  src: url('${fileName}') format('woff2');${range?.[1] ? `\n  unicode-range: ${range[1].trim()};` : ''}
}`);
    }
  }
  copyFileSync(join(base, 'LICENSE'), join(OUT, `LICENSE-${family.replace(/\s+/g, '')}.txt`));
}

const versions = FAMILIES.map(({ pkg }) => {
  const v = JSON.parse(readFileSync(join(ROOT, 'node_modules', pkg, 'package.json'), 'utf8')).version;
  return `     ${pkg}@${v}`;
}).join('\n');

writeFileSync(join(OUT, 'fonts.css'), `/* GENERATED by scripts/fonts.ts — do not edit.

   Source:
${versions}

   Both families are SIL Open Font License 1.1; the licence text ships
   beside this file. Latin and latin-ext, variable woff2 only. Regenerate with
   \`make fonts\` after a change to the face list in the script. */

${blocks.join('\n\n')}
`);

/* The characters a drawing can set: Latin, the punctuation and the signs a
   label uses. A character outside this list measures as the widest one. */
const CHARS = [
  [0x20, 0x7e], [0xa0, 0x17f], [0x2010, 0x2027], [0x2030, 0x203a], [0x2190, 0x2199],
  [0x21d2, 0x21d4], [0x2212, 0x2212], [0x2260, 0x2265], [0x2460, 0x2473], [0x2713, 0x2717],
].flatMap(([from, to]) => Array.from({ length: (to ?? 0) - (from ?? 0) + 1 }, (_, i) => (from ?? 0) + i));

/* The weights a drawing uses. Variable faces, so each is a measurement of
   its own, never a factor on the regular one. */
const MEASURED = [
  { key: 'sans', family: 'Source Sans 3', files: SUBSETS.map((s) => join(OUT, `source-sans-3-${s}-wght-normal.woff2`)), weights: [400, 600] },
  { key: 'mono', family: 'Source Code Pro', files: SUBSETS.map((s) => join(OUT, `source-code-pro-${s}-wght-normal.woff2`)), weights: [400, 600] },
];

/* What a drawing shows where the faces never arrive: an SVG opened as an
   image, or a page whose faces came late. DejaVu is the widest common
   fallback, so a line that fits it fits on every system. Measured from the
   package, never from the faces this machine happens to have. */
const DEJAVU = join(ROOT, 'node_modules', 'dejavu-fonts-ttf', 'ttf');
const FALLBACK = [
  { key: 'fallback-sans', family: 'DejaVu Sans', regular: 'DejaVuSans.ttf', bold: 'DejaVuSans-Bold.ttf', weights: [400, 600] },
  { key: 'fallback-mono', family: 'DejaVu Sans Mono', regular: 'DejaVuSansMono.ttf', bold: 'DejaVuSansMono-Bold.ttf', weights: [400, 600] },
];

const browser = await chromium.launch();
const page = await browser.newPage();
const widths: Record<string, number[]> = {};
const measureFace = async (family: string, sources: string[], weight: number, range: string): Promise<number[]> =>
  page.evaluate(
    async ({ family, sources, weight, range, chars }) => {
      for (const source of sources) {
        const bytes = Uint8Array.from(atob(source), (c) => c.charCodeAt(0));
        document.fonts.add(await new FontFace(family, bytes, { weight: range }).load());
      }
      const context = document.createElement('canvas').getContext('2d');
      if (!context) throw new Error('no 2d context');
      context.font = `${weight} 1000px "${family}"`;
      return chars.map((c) => Math.ceil(context.measureText(String.fromCodePoint(c)).width));
    },
    { family, sources, weight, range, chars: CHARS },
  );
const base64 = (file: string): string => readFileSync(file).toString('base64');

for (const face of MEASURED) {
  for (const weight of face.weights) {
    widths[`${face.key}-${weight}`] = await measureFace(face.family, face.files.map(base64), weight, '200 900');
  }
}
for (const face of FALLBACK) {
  for (const weight of face.weights) {
    const file = weight >= 600 ? face.bold : face.regular;
    const family = `${face.family} ${weight >= 600 ? 'Bold' : 'Regular'}`;
    widths[`${face.key}-${weight}`] = await measureFace(family, [base64(join(DEJAVU, file))], 400, 'normal');
  }
}
await browser.close();

const METRICS = join(FRONTEND, 'src', 'lib', 'diagram', 'metrics.generated.ts');
writeFileSync(
  METRICS,
  `/* GENERATED by scripts/fonts.ts — from fonts/. Do not edit.
   The advance of each character in thousandths of the size, per face and
   weight, and of the fallback a page shows without the faces. Measured in a
   browser. Run \`make fonts\` after a change of face. */

/** The characters measured, in the order of every list below. */
export const CHARS = ${JSON.stringify(String.fromCodePoint(...CHARS))};

export const WIDTHS: Readonly<Record<string, readonly number[]>> = {
${Object.entries(widths).map(([key, list]) => `  ${JSON.stringify(key)}: [${list.join(',')}],`).join('\n')}
};
`,
);

/* The faces a drawing carries inside itself, because a drawing shown as an
   image sees no face of the page. A static cut per weight, the variable axis
   pinned, with the characters above and nothing else. The engine puts the
   cuts that a drawing uses into its file. */
const CARRIED: Record<string, string> = {};
const RANGES: Record<string, string> = {};
for (const face of MEASURED) {
  for (const [i, subset] of SUBSETS.entries()) {
    const file = face.files[i] ?? '';
    const block = blocks.find((b) => b.includes(file.split('/').pop() ?? ''));
    const range = block ? /unicode-range:\s*([^;\n]+);/.exec(block)?.[1]?.trim() : undefined;
    if (!range) throw new Error(`${face.family}: no unicode-range for ${subset}`);
    RANGES[subset] = range;
    for (const weight of face.weights) {
      const cut = await subsetFont(readFileSync(file), String.fromCodePoint(...CHARS), { targetFormat: 'woff2', variationAxes: { wght: weight } });
      CARRIED[`${face.key}-${weight}-${subset}`] = cut.toString('base64');
    }
  }
}
writeFileSync(
  join(FRONTEND, 'src', 'lib', 'diagram', 'faces.generated.ts'),
  `/* GENERATED by scripts/fonts.ts — from fonts/. Do not edit.
   The faces a drawing carries: a static cut per face, weight and subset, as
   base64 woff2. Run \`make fonts\` after a change of face. */

/** The characters each subset covers, as a CSS unicode-range. */
export const RANGES: Readonly<Record<string, string>> = ${JSON.stringify(RANGES, null, 2)};

export const CUTS: Readonly<Record<string, string>> = {
${Object.entries(CARRIED).map(([key, data]) => `  ${JSON.stringify(key)}: ${JSON.stringify(data)},`).join('\n')}
};
`,
);

report.open('fonts', 'regenerate fonts/ from @fontsource');
report.fact('src/lib/diagram/metrics.generated.ts', `${CHARS.length} characters`);
report.fact('src/lib/diagram/faces.generated.ts', `${Object.keys(CARRIED).length} cuts, ${Math.round(Object.values(CARRIED).join('').length / 1024)} kB`);
report.summary(`${copied} woff2 \u00b7 ${blocks.length} @font-face rules \u00b7 ${FAMILIES.length} licences`);
